/**
 * In-memory annotation model.
 *
 * Annotations from the file are imported (via the Rust reader) into the same model as the ones
 * created in the app. Saving computes a diff between the current model and the "pristine"
 * snapshot taken when the document was loaded, so every save is relative to the original bytes.
 */
import type {
  AnnotKind,
  AnnotationDto,
  BorderStyle,
  ExistingAnnotation,
  LineEnding,
  Rect,
  Rgb,
  TextAlign,
} from "./dto";

export type { AnnotKind, Rect, Rgb } from "./dto";

/** Raster image attached to an image stamp / signature. */
export interface StampImage {
  /** Stable id (content hash) so identical images are sent only once per save. */
  id: string;
  width: number;
  height: number;
  /** Non-premultiplied RGBA8 pixels. */
  rgba: Uint8Array;
  /** `data:` URL used for on-screen rendering. */
  url: string;
}

/** Kinds that exist in the file but that the app cannot draw itself (rendered by pdf.js). */
export type ModelKind = AnnotKind | "other";

export interface Annotation {
  /** Model id: the object reference ("12R") for file annotations, `n:<uuid>` for new ones. */
  id: string;
  /** Object reference in the file, or null for annotations created in this session. */
  ref: string | null;
  kind: ModelKind;
  /** Raw PDF subtype (useful for "other"). */
  subtype: string;
  page: number;
  rect: Rect;
  color: Rgb | null;
  interiorColor: Rgb | null;
  opacity: number;
  borderWidth: number;
  borderStyle: BorderStyle;
  dash: number[];
  contents: string;
  author: string;
  subject: string | null;
  nm: string;
  created: string | null;
  modified: string | null;
  hidden: boolean;
  print: boolean;
  locked: boolean;
  quadPoints: number[];
  inkList: number[][];
  vertices: number[];
  line: [number, number, number, number] | null;
  lineEndings: [LineEnding, LineEnding];
  icon: string | null;
  fontSize: number;
  fontColor: Rgb | null;
  textAlign: TextAlign;
  stampLabel: string | null;
  stampSublabel: string | null;
  stampImage: StampImage | null;
  /** Model id of the annotation this one replies to. */
  inReplyTo: string | null;
  replyType: "R" | "Group" | null;
  state: string | null;
  stateModel: string | null;
  /** Can the geometry be edited / the appearance regenerated by the app? */
  editable: boolean;
  /** The file annotation has an appearance stream (pdf.js draws it). */
  hasAppearance: boolean;
  popupRef: string | null;
}

export const TEXT_MARKUP_KINDS: ReadonlySet<ModelKind> = new Set(["highlight", "underline", "strikeout", "squiggly"]);
export const SUPPORTED_KINDS: ReadonlySet<string> = new Set([
  "highlight",
  "underline",
  "strikeout",
  "squiggly",
  "note",
  "freetext",
  "ink",
  "square",
  "circle",
  "line",
  "polygon",
  "polyline",
  "stamp",
]);

/** Subtypes that are not comments and therefore never enter the model. */
const NON_COMMENT_SUBTYPES = new Set([
  "Link",
  "Widget",
  "Popup",
  "PrinterMark",
  "TrapNet",
  "Watermark",
  "3D",
  "RichMedia",
  "Screen",
  "Movie",
  "Projection",
]);

export function isTextMarkup(kind: ModelKind): boolean {
  return TEXT_MARKUP_KINDS.has(kind);
}

export function isReply(a: Annotation): boolean {
  return a.inReplyTo !== null && a.replyType !== "Group";
}

let counter = 0;
export function newId(): string {
  counter = (counter + 1) % 1_000_000;
  const rnd = crypto.getRandomValues(new Uint32Array(2));
  return `n:${Date.now().toString(36)}${counter.toString(36)}${rnd[0].toString(36)}${rnd[1].toString(36)}`;
}

export function newNm(): string {
  return `yapr-${crypto.randomUUID()}`;
}

export function normalizeRect(r: Rect): Rect {
  return [Math.min(r[0], r[2]), Math.min(r[1], r[3]), Math.max(r[0], r[2]), Math.max(r[1], r[3])];
}

export function nowIso(): string {
  return new Date().toISOString();
}

/** Default values for every field; callers override what they need. */
export function blankAnnotation(kind: ModelKind, page: number, rect: Rect): Annotation {
  return {
    id: newId(),
    ref: null,
    kind,
    subtype: kind,
    page,
    rect: normalizeRect(rect),
    color: [1, 0.83, 0],
    interiorColor: null,
    opacity: 1,
    borderWidth: 1,
    borderStyle: "solid",
    dash: [],
    contents: "",
    author: "",
    subject: null,
    nm: newNm(),
    created: nowIso(),
    modified: nowIso(),
    hidden: false,
    print: true,
    locked: false,
    quadPoints: [],
    inkList: [],
    vertices: [],
    line: null,
    lineEndings: ["None", "None"],
    icon: null,
    fontSize: 12,
    fontColor: null,
    textAlign: "left",
    stampLabel: null,
    stampSublabel: null,
    stampImage: null,
    inReplyTo: null,
    replyType: null,
    state: null,
    stateModel: null,
    editable: true,
    hasAppearance: false,
    popupRef: null,
  };
}

/** Convert one annotation read from the file into the model; `null` for non-comment annotations. */
export function fromExisting(e: ExistingAnnotation): Annotation | null {
  if (NON_COMMENT_SUBTYPES.has(e.subtype)) return null;
  const dto = e.annotation;
  const base = blankAnnotation(dto ? dto.kind : "other", e.pageIndex, e.rect);
  const a: Annotation = {
    ...base,
    id: e.ref,
    ref: e.ref,
    subtype: e.subtype,
    contents: e.contents,
    author: e.author,
    modified: e.modified,
    created: null,
    nm: "",
    hidden: (e.flags & 2) !== 0,
    print: (e.flags & 4) !== 0,
    locked: (e.flags & 128) !== 0,
    hasAppearance: e.hasAppearance,
    popupRef: e.popupRef,
    inReplyTo: e.inReplyToRef,
    replyType: e.inReplyToRef ? (e.replyType === "Group" ? "Group" : "R") : null,
    editable: false,
    color: null,
  };
  if (!dto) return a;
  return {
    ...a,
    kind: dto.kind,
    rect: normalizeRect(dto.rect),
    color: dto.color ?? null,
    interiorColor: dto.interiorColor ?? null,
    opacity: dto.opacity ?? 1,
    borderWidth: dto.borderWidth ?? 1,
    borderStyle: dto.borderStyle ?? "solid",
    dash: dto.dash ?? [],
    contents: dto.contents ?? e.contents,
    author: dto.author ?? e.author,
    subject: dto.subject ?? null,
    nm: dto.nm ?? "",
    created: dto.created ?? null,
    modified: dto.modified ?? e.modified,
    quadPoints: dto.quadPoints ?? [],
    inkList: dto.inkList ?? [],
    vertices: dto.vertices ?? [],
    line: dto.line ?? null,
    lineEndings: dto.lineEndings ?? ["None", "None"],
    icon: dto.icon ?? null,
    fontSize: dto.fontSize ?? 12,
    fontColor: dto.fontColor ?? null,
    textAlign: dto.textAlign ?? "left",
    stampLabel: dto.stampLabel ?? null,
    stampSublabel: dto.stampSublabel ?? null,
    state: dto.state ?? null,
    stateModel: dto.stateModel ?? null,
    // Stamps carry arbitrary appearance streams we cannot reproduce; everything else we can redraw.
    editable: dto.kind !== "stamp",
  };
}

/** Fields whose change requires regenerating the appearance stream. */
const VISUAL_FIELDS: (keyof Annotation)[] = [
  "kind",
  "rect",
  "color",
  "interiorColor",
  "opacity",
  "borderWidth",
  "borderStyle",
  "dash",
  "quadPoints",
  "inkList",
  "vertices",
  "line",
  "lineEndings",
  "icon",
  "fontSize",
  "fontColor",
  "textAlign",
  "stampLabel",
  "stampSublabel",
  "stampImage",
];

/** Fields whose change can be written without touching the appearance stream. */
const META_FIELDS: (keyof Annotation)[] = [
  "contents",
  "author",
  "subject",
  "hidden",
  "print",
  "locked",
  "state",
  "stateModel",
];

function same(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (Array.isArray(a) && Array.isArray(b)) {
    return a.length === b.length && a.every((v, i) => same(v, b[i]));
  }
  if (a && b && typeof a === "object" && typeof b === "object") {
    if ("id" in a && "id" in b) return (a as { id: unknown }).id === (b as { id: unknown }).id;
  }
  return false;
}

export function visualChanged(a: Annotation, b: Annotation): boolean {
  if (a.kind === "freetext" && a.contents !== b.contents) return true;
  return VISUAL_FIELDS.some((k) => !same(a[k], b[k]));
}

export function metaChanged(a: Annotation, b: Annotation): boolean {
  return META_FIELDS.some((k) => !same(a[k], b[k]));
}

/** Rect-only change (move / resize) of a non-editable annotation. */
export function rectChanged(a: Annotation, b: Annotation): boolean {
  return !same(a.rect, b.rect);
}

export function annotationChanged(a: Annotation, b: Annotation): boolean {
  return visualChanged(a, b) || metaChanged(a, b);
}

export function hexToRgb(hex: string | null | undefined): Rgb | null {
  if (!hex) return null;
  const m = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex.trim());
  if (!m) return null;
  return [parseInt(m[1], 16) / 255, parseInt(m[2], 16) / 255, parseInt(m[3], 16) / 255];
}

export function rgbToHex(rgb: Rgb | null | undefined): string | null {
  if (!rgb) return null;
  const h = (v: number) =>
    Math.round(Math.min(1, Math.max(0, v)) * 255)
      .toString(16)
      .padStart(2, "0");
  return `#${h(rgb[0])}${h(rgb[1])}${h(rgb[2])}`;
}

export function rgbToCss(rgb: Rgb | null | undefined, fallback = "transparent"): string {
  return rgbToHex(rgb) ?? fallback;
}

/**
 * Convert the model into the writer DTO. `imageIndex` maps stamp image ids to blob indices;
 * `parent` is the annotation this one replies to (if any).
 */
export function toDto(a: Annotation, imageIndex: Map<string, number>, parent?: Annotation): AnnotationDto {
  const parentRef = parent?.ref ?? null;
  return {
    kind: a.kind === "other" ? "stamp" : a.kind,
    pageIndex: a.page,
    rect: normalizeRect(a.rect),
    color: a.color,
    interiorColor: a.interiorColor,
    opacity: a.opacity,
    borderWidth: a.borderWidth,
    borderStyle: a.borderStyle,
    dash: a.dash,
    contents: a.contents,
    author: a.author,
    subject: a.subject,
    nm: a.nm,
    created: a.created,
    modified: a.modified,
    hidden: a.hidden,
    print: a.print,
    locked: a.locked,
    quadPoints: a.quadPoints,
    inkList: a.inkList,
    vertices: a.vertices,
    line: a.line,
    lineEndings: a.lineEndings,
    icon: a.icon,
    fontSize: a.fontSize,
    fontColor: a.fontColor,
    textAlign: a.textAlign,
    stampLabel: a.stampLabel,
    stampSublabel: a.stampSublabel,
    stampImage: a.stampImage
      ? { blob: imageIndex.get(a.stampImage.id) ?? 0, width: a.stampImage.width, height: a.stampImage.height }
      : null,
    inReplyToRef: parentRef,
    inReplyToNm: parent && !parentRef ? parent.nm : null,
    state: a.state,
    stateModel: a.stateModel,
    open: false,
  };
}

/** Bounding box of a list of flat point arrays. */
export function boundsOfPoints(lists: number[][], pad = 0): Rect {
  let x1 = Infinity;
  let y1 = Infinity;
  let x2 = -Infinity;
  let y2 = -Infinity;
  for (const pts of lists) {
    for (let i = 0; i + 1 < pts.length; i += 2) {
      x1 = Math.min(x1, pts[i]);
      x2 = Math.max(x2, pts[i]);
      y1 = Math.min(y1, pts[i + 1]);
      y2 = Math.max(y2, pts[i + 1]);
    }
  }
  if (!Number.isFinite(x1)) return [0, 0, 0, 0];
  return [x1 - pad, y1 - pad, x2 + pad, y2 + pad];
}

/** Human readable kind key for i18n (`kind.*`). */
export function kindLabelKey(a: Pick<Annotation, "kind" | "subtype" | "stampImage">):
  | `kind.${AnnotKind}`
  | "kind.signature"
  | "kind.other"
  | "kind.fileattachment" {
  if (a.kind === "stamp" && a.stampImage) return "kind.signature";
  if (a.kind === "other") return a.subtype === "FileAttachment" ? "kind.fileattachment" : "kind.other";
  return `kind.${a.kind}`;
}
