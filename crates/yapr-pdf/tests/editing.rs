//! Page editing: pictures as pages, mirroring, duplicating, watermarks and password protection.

mod common;

use common::*;
use lopdf::Document;
use yapr_pdf::*;

fn ops(bytes: &[u8], password: Option<&str>, ops: &[PageOp], blobs: &[&[u8]]) -> Vec<u8> {
    apply_page_ops(bytes, password, ops, blobs).unwrap()
}

/// Minimal baseline JPEG header (enough for the embedder; viewers would need real data).
fn fake_jpeg(width: u16, height: u16) -> Vec<u8> {
    let mut out = vec![0xFF, 0xD8, 0xFF, 0xC0, 0, 17, 8];
    out.extend_from_slice(&height.to_be_bytes());
    out.extend_from_slice(&width.to_be_bytes());
    out.extend_from_slice(&[3, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1, 0xFF, 0xD9]);
    out
}

/// The page's MediaBox, following `/Parent` for inherited values.
fn media_box(doc: &Document, index: usize) -> Vec<f64> {
    let mut dict = page(doc, index);
    loop {
        if let Ok(value) = dict.get(b"MediaBox") {
            return numbers(value);
        }
        let parent = dict.get(b"Parent").unwrap().as_reference().unwrap();
        dict = doc.get_dictionary(parent).unwrap();
    }
}

fn content(doc: &Document, index: usize) -> String {
    String::from_utf8_lossy(&doc.get_page_content(page_ids(doc)[index])).into_owned()
}

#[test]
fn pictures_become_pages() {
    let sample = sample();
    let rgba = vec![255u8; 4 * 40 * 20];
    let jpeg = fake_jpeg(300, 600);
    let images = vec![
        PageImage { blob: 0, format: ImageFormat::Rgba, width: 40, height: 20 },
        PageImage { blob: 1, format: ImageFormat::Jpeg, width: 0, height: 0 },
    ];
    // Original size (96 dpi): 40×20 px → 30×15 pt; 300×600 px → 225×450 pt.
    let out = ops(&sample.bytes, None, &[PageOp::InsertImages { at: 1, images: images.clone(), page_size: None, margin: 0.0 }], &[&rgba, &jpeg]);
    let doc = load(&out, None);
    assert_eq!(page_ids(&doc).len(), 5);
    assert_eq!(media_box(&doc, 1), vec![0.0, 0.0, 30.0, 15.0]);
    assert_eq!(media_box(&doc, 2), vec![0.0, 0.0, 225.0, 450.0]);
    assert_eq!(markers(&out, None)[0], "PAGE-A");
    assert_eq!(markers(&out, None)[3], "PAGE-B");
    // A4 pages: landscape for the wide picture, portrait for the tall one.
    let out = ops(&sample.bytes, None, &[PageOp::InsertImages { at: 3, images, page_size: Some([595.0, 842.0]), margin: 20.0 }], &[&rgba, &jpeg]);
    let doc = load(&out, None);
    assert_eq!(media_box(&doc, 3), vec![0.0, 0.0, 842.0, 595.0]);
    assert_eq!(media_box(&doc, 4), vec![0.0, 0.0, 595.0, 842.0]);
    let jpeg_page = page(&doc, 4);
    let xobjects = jpeg_page.get(b"Resources").unwrap().as_dict().unwrap().get(b"XObject").unwrap().as_dict().unwrap();
    let image = doc.get_object(xobjects.get(b"Im0").unwrap().as_reference().unwrap()).unwrap().as_stream().unwrap();
    assert_eq!(image.dict.get(b"Filter").unwrap().as_name().unwrap(), b"DCTDecode");
    assert_eq!(image.content, jpeg, "JPEG data is embedded unchanged");
    std::fs::write(output_dir().join("image_pages.pdf"), &out).unwrap();

    let err = apply_page_ops(&sample.bytes, None, &[PageOp::InsertImages { at: 0, images: vec![PageImage { blob: 0, format: ImageFormat::Jpeg, width: 0, height: 0 }], page_size: None, margin: 0.0 }], &[b"not a jpeg"]).unwrap_err();
    assert!(matches!(err, PdfError::InvalidRequest(_)));
}

#[test]
fn flip_mirrors_content_and_comments() {
    let sample = sample();
    // Page C (index 2) has a square annotation.
    let before = load(&sample.bytes, None);
    let square_before = page_annots(&before, 2).into_iter().find(|(_, d)| subtype(d) == "Square").unwrap().1;
    let rect_before = numbers(square_before.get(b"Rect").unwrap());
    let out = ops(&sample.bytes, None, &[PageOp::Flip { pages: vec![2, 0], horizontal: true }], &[]);
    assert!(out.starts_with(&sample.bytes), "flip is an incremental update");
    let doc = load(&out, None);
    assert_eq!(markers(&out, None), vec!["PAGE-A", "PAGE-B", "PAGE-C"]);
    // Page A is upright: a horizontal flip mirrors x around the page width.
    assert!(content(&doc, 0).contains("-1 0 0 1 595 0 cm"));
    // Page C is displayed rotated by 90°: the displayed horizontal flip mirrors user-space y.
    let height = media_box(&doc, 2)[3];
    assert!(content(&doc, 2).contains(&format!("1 0 0 -1 0 {} cm", height as i64)));
    let square = page_annots(&doc, 2).into_iter().find(|(_, d)| subtype(d) == "Square").unwrap().1;
    let rect = numbers(square.get(b"Rect").unwrap());
    assert!((rect[0] - rect_before[0]).abs() < 0.01);
    assert!((rect[1] - (height - rect_before[3])).abs() < 0.01);
    assert!(!square.has(b"AP"), "geometric appearance is regenerated by viewers");
    // Rotated page B (/Rotate 90 inherited): a displayed horizontal flip mirrors user-space y.
    let out = ops(&sample.bytes, None, &[PageOp::Flip { pages: vec![1], horizontal: true }], &[]);
    let doc = load(&out, None);
    assert!(content(&doc, 1).contains("1 0 0 -1 0"));
}

#[test]
fn duplicate_copies_pages_and_comments() {
    let sample = sample();
    let out = ops(&sample.bytes, None, &[PageOp::Duplicate { pages: vec![2, 0], at: 3 }], &[]);
    assert_eq!(markers(&out, None), vec!["PAGE-A", "PAGE-B", "PAGE-C", "PAGE-C", "PAGE-A"]);
    let doc = load(&out, None);
    let ids = page_ids(&doc);
    let original = page_annots(&doc, 2);
    let copied = page_annots(&doc, 3);
    assert_eq!(original.len(), copied.len());
    for (id, dict) in &copied {
        assert!(original.iter().all(|(o, _)| o != id), "annotations are new objects");
        assert_eq!(dict.get(b"P").unwrap().as_reference().unwrap(), ids[3]);
    }
    let read = read_annotations(&out, None).unwrap();
    assert_eq!(read.iter().filter(|a| a.page_index == 3).count(), copied.len());
}

#[test]
fn watermark_text_and_picture() {
    let sample = sample();
    let text = WatermarkSpec {
        text: Some("CONFIDENTIAL\n机密文件".into()),
        font_size: 40.0,
        bold: true,
        color: [0.8, 0.1, 0.1],
        image: None,
        image_scale: 0.4,
        opacity: 0.25,
        rotation: 45.0,
        position: WatermarkPosition::Tile,
        layer: WatermarkLayer::Above,
        cjk_hint: Some("zh-CN".into()),
    };
    let out = ops(&sample.bytes, None, &[PageOp::Watermark { pages: vec![0, 1, 2], watermark: text.clone() }], &[]);
    assert!(out.starts_with(&sample.bytes));
    assert_eq!(markers(&out, None), vec!["PAGE-A", "PAGE-B", "PAGE-C"]);
    let doc = load(&out, None);
    for i in 0..3 {
        let c = content(&doc, i);
        assert!(c.contains("/Subtype /Watermark>> BDC"), "page {i}");
        assert!(c.matches("/YaprWm0 Do").count() > 3, "tiled on page {i}");
        // Existing resources are kept.
        let resources = page(&doc, i).get(b"Resources").unwrap().as_dict().unwrap();
        assert!(resources.get(b"Font").is_ok());
    }
    std::fs::write(output_dir().join("watermark_text.pdf"), &out).unwrap();

    let rgba = vec![200u8; 4 * 10 * 10];
    let picture = WatermarkSpec {
        text: None,
        image: Some(PageImage { blob: 0, format: ImageFormat::Rgba, width: 10, height: 10 }),
        position: WatermarkPosition::BottomRight,
        layer: WatermarkLayer::Below,
        rotation: 0.0,
        ..text
    };
    let out = ops(&sample.bytes, None, &[PageOp::Watermark { pages: vec![0], watermark: picture }], &[&rgba]);
    let doc = load(&out, None);
    let c = content(&doc, 0);
    assert!(c.find("/YaprWm0 Do").unwrap() < c.find("PAGE-A").unwrap(), "below the content");
    assert_eq!(c.matches("/YaprWm0 Do").count(), 1);
    std::fs::write(output_dir().join("watermark_picture.pdf"), &out).unwrap();
}

#[test]
fn protected_documents_stay_editable() {
    let sample = sample();
    let settings = SecuritySettings {
        open_password: "open".into(),
        permissions_password: "".into(),
        permissions: DocumentPermissions::ALL,
    };
    let locked = set_security(&sample.bytes, None, None, &settings).unwrap();
    assert!(page_count(&locked, None).is_err());
    assert_eq!(markers(&locked, Some("open")), vec!["PAGE-A", "PAGE-B", "PAGE-C"]);
    // Page operations and comments are written into the encrypted document.
    let out = ops(&locked, Some("open"), &[PageOp::Rotate { pages: vec![0], delta: 90 }, PageOp::Delete { pages: vec![1] }], &[]);
    assert_eq!(markers(&out, Some("open")), vec!["PAGE-A", "PAGE-C"]);
    let changes = DocumentChanges {
        annotations: AnnotationChanges { add: vec![dto(AnnotKind::Square, 0, [10.0, 10.0, 100.0, 100.0])], ..Default::default() },
        ..Default::default()
    };
    let out = apply_document_changes(&out, Some("open"), &changes, &[]).unwrap();
    assert!(read_annotations(&out, Some("open")).unwrap().iter().any(|a| a.page_index == 0));
    assert!(security_info(&out, Some("open")).unwrap().encrypted);
    std::fs::write(output_dir().join("protected.pdf"), &out).unwrap();
    // The RC4 sample can be re-protected with AES-256 and unlocked again.
    let rc4 = encrypted_sample();
    let info = security_info(&rc4.bytes, Some(USER_PASSWORD)).unwrap();
    assert_eq!(info.method.as_deref(), Some("RC4 128-bit"));
    let aes = set_security(&rc4.bytes, Some(USER_PASSWORD), None, &settings).unwrap();
    assert_eq!(security_info(&aes, Some("open")).unwrap().method.as_deref(), Some("AES-256"));
    let plain = remove_security(&aes, Some("open"), None).unwrap();
    assert_eq!(markers(&plain, None), vec!["PAGE-A", "PAGE-B", "PAGE-C"]);
}
